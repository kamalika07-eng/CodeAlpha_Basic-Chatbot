# Step 1: Create chatbot function

def chatbot():

    print("==============================")
    print("       WELCOME TO CHATBOT")
    print("==============================")

    print("Hello! I am a simple Python chatbot.")
    print("You can talk to me.")
    print("Type 'bye' to exit.")

    # Step 2: Start conversation loop

    while True:

        user = input("\nYou: ").lower()

        # Step 3: Check user message

        if user == "hello" or user == "hi":
            print("Bot: Hi! Welcome!")

        elif user == "how are you":
            print("Bot: I'm fine, thanks! How are you?")

        elif user == "what is your name":
            print("Bot: I am a Python chatbot.")

        elif user == "what can you do":
            print("Bot: I can respond to simple messages.")

        elif user == "thank you" or user == "thanks":
            print("Bot: You're welcome!")

        elif user == "bye":
            print("Bot: Goodbye! Have a nice day.")
            break

        else:
            print("Bot: Sorry, I don't understand that message.")

# Step 4: Call chatbot function

chatbot()